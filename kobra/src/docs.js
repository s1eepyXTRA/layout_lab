/** Один раздел: `<details>` с вводной строкой и содержимым. */
function docsSection(d) {
  const box = h('details', { class: 'doc-sec' },
    h('summary', null, h('b', null, d.title), h('span', { class: 'muted' }, d.lead)));
  const inner = h('div', { class: 'doc-body' });
  d.body().forEach(part => {
    if (part.note) { inner.appendChild(h('div', { class: 'ai-note' }, part.note)); return; }
    if (part.t) inner.appendChild(h('p', null, part.t));
    if (part.items) inner.appendChild(h('ul', null, part.items.map(i => h('li', null, i))));
  });
  box.appendChild(inner);
  return box;
}

function renderDocs(main) {
  const page = h('div', { class: 'page doc-page' });
  main.appendChild(page);
  page.appendChild(h('div', { class: 'page-head' },
    h('div', { class: 'grow' }, h('h1', null, 'Документация'),
      h('p', null, 'Как собрать макет дашборда и что с ним делать дальше. '
        + (docsServer() ? 'Работа хранится в сервисе.' : 'Работа хранится в этом браузере.'))),
    h('a', { class: 'btn', href: '#/dashboards' }, 'К шаблонам')));
  DOCS.forEach(d => page.appendChild(docsSection(d)));
  page.appendChild(h('p', { class: 'muted', style: { margin: '20px 0 0', fontSize: '12.5px' } },
    'Кобра — прототип: он нужен, чтобы договориться о виде дашборда до того, как его начнут собирать.'));
}
