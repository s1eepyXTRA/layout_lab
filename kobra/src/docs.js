/* ============================================================
   Кобра · документация для человека
   Отдельная страница `#/docs`: про Кобру не было написано нигде, кроме
   README репозитория, а его читает тот, кто открыл исходники. Человек,
   которому дали ссылку на сервис, видит четыре карточки и догадывается
   сам — половина возможностей (простая правка, макет, выгрузка ТЗ,
   обмен файлами) не видна, пока не наткнёшься.

   Подсказками внутри экранов это не лечится: в интерфейсе правило «одна
   короткая строка, остальное в title или нигде». Документация — третье
   исключение из него, после подтверждений необратимых действий и выгрузки
   ТЗ, и ровно потому, что она отдельная страница, а не текст поверх
   рабочего экрана.

   Разделы — на `<details>`: разворачивание уже есть в браузере, работает
   с клавиатуры, читается экранными читалками и находится поиском по
   странице (Ctrl+F раскрывает закрытый раздел). Свой аккордеон дал бы то
   же, но без этих четырёх свойств.

   Текст описан данными (`DOCS`), а не разметкой: добавить раздел — значит
   дописать запись, а не возиться с DOM. Через `marked` его не гоняем:
   Markdown-блоки дашборда проходят через DOMPurify, потому что их пишет
   человек, а этот текст пишем мы — лишний разбор и потеря контроля над
   разметкой.
   ============================================================ */

