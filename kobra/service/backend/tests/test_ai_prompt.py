"""Системный промпт на сервере обязан совпадать с клиентским.

Копий две, и это сознательно: промпт нужен серверу (он собирает запрос) и
клиенту (офлайн-сборке обращаться больше некуда, там остаётся перенос вручную).
Отдавать промпт клиенту по сети, «чтобы копия была одна», значит вернуть
пересылку `messages` с другой стороны — то есть снова сделать из сервиса
универсальный прокси к модели.

Поэтому дублирование прикрыто тестом, как `app/guess.py` против `datasets.js`.
Разойдутся копии — разойдутся и ответы модели в зависимости от того, в каком
режиме человек работает, а разбирает их один и тот же код.
"""
import os

from app.ai import AI_SYSTEM, build_user_message

AIDRAFT_JS = os.path.normpath(os.path.join(
    os.path.dirname(__file__), "..", "..", "..", "src", "aidraft.js"))


def _promt_iz_klienta() -> str:
    """Собрать AI_TPL_SYSTEM из исходника клиента ровно так, как его собирает
    браузер: элементы массива через перевод строки (`join`), а склейка через
    `+` внутри элемента — без разделителя. Сравнение получается точным, до
    пробела: нормализуй его — и пропадёт разница между «однойстрокой» и «одной
    строкой».
    """
    src = open(AIDRAFT_JS, encoding="utf-8").read()
    body = src.split("const AI_TPL_SYSTEM = [", 1)[1].split("].join(", 1)[0]
    элементы, куски, i = [], [], 0
    while i < len(body):
        c = body[i]
        if c == "'":                       # строковый литерал
            j, буква = i + 1, []
            while j < len(body) and body[j] != "'":
                if body[j] == "\\":
                    буква.append(body[j + 1])
                    j += 2
                    continue
                буква.append(body[j])
                j += 1
            куски.append("".join(буква))
            i = j + 1
            continue
        if c == ",":                        # запятая вне строки — конец элемента
            элементы.append("".join(куски))
            куски = []
        i += 1
    if куски:
        элементы.append("".join(куски))
    элементы = [e for e in элементы if e]
    assert len(элементы) >= 6, "не разобрался исходник клиента: промпт не найден"
    return "\n".join(элементы)


def test_promt_sovpadaet_s_klientskim():
    assert AI_SYSTEM == _promt_iz_klienta()


def test_promt_ne_pustoi():
    """Страховка от разбора, который «совпал» на двух пустых строках."""
    assert len(AI_SYSTEM) > 500
    assert "Кобра" in AI_SYSTEM and "JSON" in AI_SYSTEM


def test_zapros_sobiraetsya_iz_chastei():
    """Текст запроса собирает сервер — повторяя `aiTplPrompt` в клиенте."""
    только_задача = build_user_message("заявки по этапам")
    assert только_задача == "Задача: заявки по этапам"

    с_черновиком = build_user_message(
        "убери круговую",
        {"название": "Заявки", "колонки": [{"подпись": "Статус", "тип": "string"}], "блоки": []},
        [{"название": "Воронка", "ошибка": "нет колонки этапа"}],
    )
    assert с_черновиком.startswith("Задача: убери круговую")
    assert "=== ЧТО УЖЕ СОБРАНО ===" in с_черновиком
    assert '"подпись": "Статус"' in с_черновиком
    assert "=== ЧТО НЕ ПОСТРОИЛОСЬ ===" in с_черновиком
    assert "- Воронка: нет колонки этапа" in с_черновиком
